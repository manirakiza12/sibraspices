import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const html=fs.readFileSync('dist/index.html','utf8');
const css=fs.readFileSync('dist/style.css','utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'IDs must be unique');
const anchors=[...html.matchAll(/href="#([^"]+)"/g)].map(m=>m[1]);
for(const id of anchors)assert(ids.includes(id),'Missing section: '+id);
const images=[...html.matchAll(/<img[^>]+src="([^"]+)"/g)].map(m=>m[1]);
for(const src of images)assert(fs.existsSync(path.join('dist',src)),'Missing photograph: '+src);
for(const file of ['banner1.jpg','banner2.jpg','banner3.jpg','cardamom.jpg','cumin.jpg','cinnamon.jpg','storefront.jpg'])assert(images.some(s=>s.endsWith(file)),file+' must be used');
for(const value of ['75,000','40,000','25,000','0763415857','0756776107','Kafumbe Mukasa','Owino Market','13.1K+','81.3K+','@sibraspices'])assert(html.includes(value),'Missing brand data: '+value);
assert.equal((html.match(/class="hero-slide /g)||[]).length,3);
assert.equal((html.match(/class="product-card /g)||[]).length,4);
assert(!html.includes('Jemila')&&!html.includes('Jonz'));
assert(!css.includes('@apply')&&!css.includes('@import "tailwindcss"'));
for(const token of ['.grid','.bg-burgundy','.text-herb','.hero-slide','prefers-reduced-motion','opacity-0','invisible','pointer-events-none','padding-bottom: calc(var(--spacing) * 24)'])assert(css.includes(token),'Missing compiled style: '+token);
assert.equal(css,fs.readFileSync('style.css','utf8'));
assert.equal(html,fs.readFileSync('index.html','utf8'));
assert(html.includes('defer src="./main.js"'));
assert(html.includes('href="./style.css"'));
console.log(`SIBRA static checks passed: ${images.length} photos, ${anchors.length} section links, prices, contacts, slider structure, and compiled responsive Tailwind CSS.`);
